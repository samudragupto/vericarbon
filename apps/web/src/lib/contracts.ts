import {
  CARBON_REGISTRY_ABI,
  HALO2_VERIFIER_ABI,
  DEPLOYMENT_ADDRESSES,
} from "@vericarbon/sdk";
import type { Address } from "viem";

export const CARBON_REGISTRY_ADDRESS = (
  process.env.NEXT_PUBLIC_VERICARBON_REGISTRY_ADDRESS &&
  process.env.NEXT_PUBLIC_VERICARBON_REGISTRY_ADDRESS !== "0x0000000000000000000000000000000000000000"
    ? process.env.NEXT_PUBLIC_VERICARBON_REGISTRY_ADDRESS
    : DEPLOYMENT_ADDRESSES.CarbonRegistry
) as Address;

export const HALO2_VERIFIER_ADDRESS = (
  process.env.NEXT_PUBLIC_EZKL_VERIFIER_ADDRESS &&
  process.env.NEXT_PUBLIC_EZKL_VERIFIER_ADDRESS !== "0x0000000000000000000000000000000000000000"
    ? process.env.NEXT_PUBLIC_EZKL_VERIFIER_ADDRESS
    : DEPLOYMENT_ADDRESSES.Halo2Verifier
) as Address;

export { CARBON_REGISTRY_ABI, HALO2_VERIFIER_ABI };

